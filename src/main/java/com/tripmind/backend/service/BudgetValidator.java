
package com.tripmind.backend.service;

import java.math.BigDecimal;

import org.springframework.stereotype.Component;

import com.tripmind.backend.dto.AiItineraryResponse;
import com.tripmind.backend.dto.BudgetBreakdown;

@Component
public class BudgetValidator {

    public AiItineraryResponse validateAndCalculate(
            AiItineraryResponse response,
            long userBudget) {

        // 1. Check AI response
        if (response == null) {
            throw new IllegalArgumentException(
                    "AI response cannot be null"
            );
        }

        // 2. Check user budget
        if (userBudget <= 0) {
            throw new IllegalArgumentException(
                    "Budget must be greater than zero"
            );
        }

        // 3. Check expense breakdown
        BudgetBreakdown expenses = response.getExpenses();

        if (expenses == null) {
            throw new IllegalArgumentException(
                    "AI response does not contain expense breakdown"
            );
        }

        // 4. Check all five categories
        Double[] amounts = {
            expenses.getAccommodation(),
            expenses.getFood(),
            expenses.getTransport(),
            expenses.getActivities(),
            expenses.getMiscellaneous()
        };

        for (Double amount : amounts) {

            // Missing category
            if (amount == null) {
                throw new IllegalArgumentException(
                        "AI response contains a missing expense category"
                );
            }

            // Negative, NaN or Infinity
            if (!Double.isFinite(amount) || amount < 0) {
                throw new IllegalArgumentException(
                        "Invalid expense amount generated by AI"
                );
            }
        }

        // 5. Calculate total expenses
        BigDecimal total = BigDecimal.ZERO;

        for (Double amount : amounts) {
            total = total.add(BigDecimal.valueOf(amount));
        }

        // 6. Compare with user budget
        BigDecimal budget = BigDecimal.valueOf(userBudget);

        if (total.compareTo(budget) > 0) {
            throw new IllegalArgumentException(
                    "Generated itinerary exceeds your budget"
            );
        }

        // 7. Calculate remaining budget
        BigDecimal remaining = budget.subtract(total);

        // 8. Never trust AI-calculated totals
        response.setBudget(userBudget);
        response.setEstimatedCost(total.doubleValue());
        response.setRemainingBudget(remaining.doubleValue());

        return response;
    }
}
