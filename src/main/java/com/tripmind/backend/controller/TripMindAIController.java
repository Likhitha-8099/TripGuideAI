package com.tripmind.backend.controller;

import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RestController;
import org.springframework.web.server.ResponseStatusException;

import com.tripmind.backend.dto.ApiResponse;
import com.tripmind.backend.dto.TripRequest;
import com.tripmind.backend.dto.TripResponse;
import com.tripmind.backend.service.TripMindAssistant;

import jakarta.validation.Valid;

@RestController
public class TripMindAIController {
	
	private final TripMindAssistant assistant;
	
	public TripMindAIController(TripMindAssistant assistant) {
		this.assistant=assistant;
	}
	
	@PostMapping("/api/ai/assistant")
	public ResponseEntity<ApiResponse<TripResponse>> chat(@Valid @RequestBody TripRequest tripRequest) {
		TripResponse response = assistant.generateTrip(
	            tripRequest.getDestination(),
	            tripRequest.getNumberOfDays(),
	            tripRequest.getBudget(),
	            tripRequest.getTravelStyle()
	    );

	    // Step 2: Get AI estimated cost
	    double estimatedCost = response.getEstimatedCost();
        
	    if (estimatedCost <= 0) {
	        throw new ResponseStatusException(
	                HttpStatus.BAD_REQUEST,
	                "Invalid estimated trip cost generated by AI!"
	        );
	    }
	    // Step 3: Validate budget
	    if (estimatedCost > tripRequest.getBudget()) {
	        throw new ResponseStatusException(
	                HttpStatus.BAD_REQUEST,
	                "Estimated trip cost exceeds your budget!"
	        );
	    }

	    // Step 4: Calculate remaining budget using Java
	    double remainingBudget = tripRequest.getBudget() - estimatedCost;

	    // Step 5: Update response
	    response.setRemainingBudget(remainingBudget);
        
	    ApiResponse<TripResponse> apiResponse =
	            new ApiResponse<>(
	                    true,
	                    "Trip generated successfully",
	                    response
	            );

	    return ResponseEntity.ok(apiResponse);
	   
	}

}
